//=============================================================================
// CommandQueue.h
//   GPU へ命令を送るキューと、CPU / GPU の同期を担当するクラス。
//
//   ■ DirectX 12 で最初に理解すべき「非同期」の話
//     DirectX 12 では、C++ のコードが GPU に対して命令を「直接」実行させる
//     ことはできません。次の 3 段階を踏みます。
//
//       1. コマンドリスト (ID3D12GraphicsCommandList) に命令を「記録」する
//            例）「この色でクリアして」「この三角形を描いて」
//            この時点では GPU は何もしていません。ただのメモ書きです。
//
//       2. コマンドキュー (ID3D12CommandQueue) に「投入」する
//            ExecuteCommandLists で GPU の実行待ち行列に並べます。
//            この関数は GPU の完了を待たずに即座に戻ります（非同期）。
//
//       3. GPU が自分のペースで実行する
//            CPU は次のフレームの準備を並行して進められます。
//            これが DirectX 12 が高速な理由です。
//
//   ■ そこで問題になること
//     CPU が「GPU がまだ読んでいるメモリ」を書き換えてしまうと、
//     描画結果が壊れます。かといって毎回待っていては並列化の意味がありません。
//     この「いつ待つか」を制御するのがフェンス (Fence) です。
//
//   ■ フェンス (ID3D12Fence) の仕組み
//     フェンスは GPU と CPU が共有する「単なる 64bit のカウンタ」です。
//
//       ・CPU が Signal(値 N) をキューに積む
//           → GPU がそこまでの命令を実行し終えた瞬間、カウンタが N になる
//       ・CPU は fence->GetCompletedValue() でカウンタを読む
//           → N 以上なら「N までの仕事は完了済み」と判断できる
//
//     つまり「番号札」です。GPU の作業に番号を振り、
//     「◯番まで終わった？」と CPU が確認できるようにする仕組みです。
//=============================================================================
#pragma once

#include "../Common/GraphicsCommon.h"

namespace dx12
{
class CommandQueue
{
public:
    CommandQueue() = default;
    ~CommandQueue();

    CommandQueue(const CommandQueue&) = delete;
    CommandQueue& operator=(const CommandQueue&) = delete;

    //-------------------------------------------------------------------------
    // 初期化
    //   @param device 生成に使う D3D12 デバイス
    //   @param type   キューの種類（既定は DIRECT）
    //
    //   ■ キューの種類
    //     D3D12_COMMAND_LIST_TYPE_DIRECT  … 何でもできる万能キュー（描画・計算・コピー）
    //     D3D12_COMMAND_LIST_TYPE_COMPUTE … 計算シェーダー専用
    //     D3D12_COMMAND_LIST_TYPE_COPY    … リソース転送専用
    //     COMPUTE / COPY は GPU 内の専用ハードウェアを使うため、
    //     DIRECT と並列に動かせて高速化できます（今回は DIRECT のみ使用）。
    //-------------------------------------------------------------------------
    void Initialize(ID3D12Device* device,
                    D3D12_COMMAND_LIST_TYPE type = D3D12_COMMAND_LIST_TYPE_DIRECT);

    //-------------------------------------------------------------------------
    // 記録済みのコマンドリストを GPU の実行待ち行列へ投入する
    //   この関数は GPU の完了を待たず、すぐに戻ります。
    //-------------------------------------------------------------------------
    void ExecuteCommandList(ID3D12GraphicsCommandList* commandList);

    //-------------------------------------------------------------------------
    // 「ここまでの仕事が終わったら番号を進めて」という指示をキューに積む
    //   @return 積んだ番号（この値を WaitForFenceValue に渡す）
    //-------------------------------------------------------------------------
    uint64_t Signal();

    //-------------------------------------------------------------------------
    // 指定した番号まで GPU が到達するのを CPU 側で待つ
    //   すでに到達済みなら即座に戻ります（無駄な待ちは発生しません）。
    //-------------------------------------------------------------------------
    void WaitForFenceValue(uint64_t fenceValue);

    //-------------------------------------------------------------------------
    // GPU の作業が「全部」終わるまで待つ（Signal + WaitForFenceValue）
    //
    //   使いどころ:
    //     ・アプリ終了時（GPU が使用中のリソースを解放しないため。必須）
    //     ・スワップチェーンのサイズ変更前（バックバッファを差し替えるため。必須）
    //
    //   ※ 毎フレーム呼ぶと CPU と GPU が完全に直列化し、性能が大きく落ちます。
    //     本プロジェクトの第 1 段階では「分かりやすさ優先」で毎フレーム呼びますが、
    //     これは意図的な単純化です（docs/03 に改善案を記載）。
    //-------------------------------------------------------------------------
    void Flush();

    // --- 参照用アクセサ ------------------------------------------------------
    ID3D12CommandQueue* Get() const noexcept { return m_commandQueue.Get(); }

private:
    ComPtr<ID3D12CommandQueue> m_commandQueue;

    // GPU と共有するカウンタ本体
    ComPtr<ID3D12Fence> m_fence;

    // CPU 側が「次に発行する番号」を覚えておく変数。
    // フェンス本体のカウンタ（GPU が進める）とは別物であることに注意。
    uint64_t m_nextFenceValue = 0;

    //-------------------------------------------------------------------------
    // 待機用の Windows イベントオブジェクト
    //
    //   GPU の完了を待つ方法は 2 通りあります。
    //     (a) while (fence->GetCompletedValue() < value) {}  … ビジーループ
    //         → CPU コアを 100% 使い切って待つため、電力も性能も無駄。
    //     (b) イベントで待つ（本実装）
    //         → OS にスレッドを寝かせてもらい、完了時に起こしてもらう。
    //            待っている間、CPU を他の処理に譲れる。
    //-------------------------------------------------------------------------
    HANDLE m_fenceEvent = nullptr;
};

} // namespace dx12
