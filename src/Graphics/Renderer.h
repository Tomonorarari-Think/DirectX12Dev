//=============================================================================
// Renderer.h
//   ここまでの部品（デバイス／キュー／スワップチェーン／パイプライン）を束ね、
//   「1 フレーム描く」という仕事を担当するクラス。
//
//   ■ 1 フレームの流れ（Render() の中身）
//
//     0. このバックバッファを前回使ったときの GPU 処理の完了を待つ
//     1. コマンドアロケータをリセット   … そのフレーム用の記録メモリを再利用する
//     2. コマンドリストをリセット       … 記録を開始する（この時点で「開いた」状態）
//     3. リソースバリア（PRESENT → RENDER_TARGET）
//     4. ビューポート / シザー矩形を設定 … 画面のどこに描くかを指定
//     5. レンダーターゲットを設定       … どこに描くかを指定
//     6. 画面をクリア                   … 背景色で塗りつぶす
//     7. 三角形の描画命令を記録
//     8. リソースバリア（RENDER_TARGET → PRESENT）
//     9. コマンドリストを Close        … 記録を終了
//    10. コマンドキューへ投入           … ここで初めて GPU が動き始める
//    11. Present                       … 画面に表示
//    12. フェンス値を記録               … 「このフレームの完了印」を予約する
//
//   ■ コマンドアロケータ (ID3D12CommandAllocator) とは
//     コマンドリストに記録した命令が実際に格納されるメモリの持ち主です。
//     コマンドリストは「記録するためのペン」、アロケータは「ノート」に相当します。
//
//     重要な制約:
//       アロケータの Reset() は「そのノートに書かれた命令を GPU が実行し終えた後」
//       でなければ呼べません。実行中のノートを消しゴムで消すようなもので、
//       GPU がクラッシュします。
//       この制約こそが、フレーム間の同期（フェンス）が必要な最大の理由です。
//
//   ■ フレームバッファリング（このクラスの中核）
//
//     素直に上の制約を満たすなら「毎フレーム末尾で GPU の完了を待つ」で済みます。
//     しかしそれでは CPU と GPU が交互にしか動けません。
//
//       CPU: [記録]              [記録]              [記録]
//       GPU:        [実行][待機]        [実行][待機]        [実行]
//
//     そこで「ノート（アロケータ）をバックバッファの枚数ぶん用意する」ことで、
//     GPU がノート 0 を実行している間に CPU がノート 1 へ書き込めるようにします。
//
//       CPU: [記録0][記録1][記録2][記録3]...
//       GPU:        [実行0][実行1][実行2]...
//                   └ CPU が 1 フレーム先行できる
//
//     待つのは「今から使おうとしているノートが空いたか」だけです。
//     そのために、フレームごとに Signal() したフェンス値を配列で覚えておき、
//     同じ番号のノートを再び使うときにその値だけを待ちます。
//=============================================================================
#pragma once

#include "../Common/FrameTimer.h"
#include "../Common/GraphicsCommon.h"
#include "CommandQueue.h"
#include "GraphicsDevice.h"
#include "SwapChain.h"
#include "TrianglePipeline.h"

#include <array>

namespace dx12
{
class Renderer
{
public:
    Renderer() = default;
    ~Renderer();

    Renderer(const Renderer&) = delete;
    Renderer& operator=(const Renderer&) = delete;

    //-------------------------------------------------------------------------
    // 初期化
    //   @param hwnd   描画先のウィンドウ
    //   @param width  初期の描画解像度（幅）
    //   @param height 初期の描画解像度（高さ）
    //-------------------------------------------------------------------------
    void Initialize(HWND hwnd, uint32_t width, uint32_t height);

    // 1 フレーム描画する
    void Render();

    //-------------------------------------------------------------------------
    // ウィンドウサイズ変更に追従する
    //   内部で GPU の完了待ちを行ってからスワップチェーンを作り直します。
    //-------------------------------------------------------------------------
    void Resize(uint32_t width, uint32_t height);

    //-------------------------------------------------------------------------
    // GPU の全作業完了を待つ（終了時に必ず呼ぶこと）
    //
    //   これを忘れると、GPU がまだ使用中のリソースを CPU 側が解放してしまい、
    //   終了時にクラッシュしたり、デバッグレイヤーが警告を出したりします。
    //-------------------------------------------------------------------------
    void WaitForGpu();

private:
    // コマンドアロケータとコマンドリストを生成する
    void CreateCommandObjects();

    // ビューポートとシザー矩形をウィンドウサイズに合わせて更新する
    void UpdateViewportAndScissor(uint32_t width, uint32_t height);

    //-------------------------------------------------------------------------
    // リソースバリアを記録するヘルパー
    //
    //   ■ リソースバリア (Resource Barrier) とは
    //     「このリソースの用途を今から変えます」と GPU に宣言する命令です。
    //
    //     GPU 内部では、同じメモリでも用途によって最適な保持形式が異なります
    //     （描画先として書き込むとき用に圧縮された状態、テクスチャとして
    //       読むとき用の状態、画面表示用の状態…）。
    //     用途を切り替えるときは、この宣言によって
    //     「形式の変換」と「それ以前の処理の完了待ち」を GPU に行わせます。
    //
    //     DirectX 11 ではドライバが自動でやっていました。DirectX 12 では
    //     開発者が明示する代わりに、不要なバリアを省いて高速化できます。
    //     逆に言えば、書き忘れると描画結果が壊れる・クラッシュする原因になります。
    //-------------------------------------------------------------------------
    static void RecordResourceBarrier(ID3D12GraphicsCommandList* commandList,
                                      ID3D12Resource* resource,
                                      D3D12_RESOURCE_STATES stateBefore,
                                      D3D12_RESOURCE_STATES stateAfter);

private:
    GraphicsDevice   m_graphicsDevice;   // デバイス・ファクトリ
    CommandQueue     m_commandQueue;     // コマンドキュー・フェンス
    SwapChain        m_swapChain;        // バックバッファ・RTV
    TrianglePipeline m_trianglePipeline; // PSO・頂点バッファ

    //-------------------------------------------------------------------------
    // コマンドアロケータ（バックバッファの枚数ぶん用意する）
    //
    //   フレーム N では m_commandAllocators[N % kBackBufferCount] を使います。
    //   GPU がまだ [0] の命令を実行中でも、CPU は [1] に記録を始められます。
    //-------------------------------------------------------------------------
    std::array<ComPtr<ID3D12CommandAllocator>, SwapChain::kBackBufferCount> m_commandAllocators;

    //-------------------------------------------------------------------------
    // コマンドリストは 1 本で足ります。
    //   Reset() のたびに「どのアロケータへ書くか」を指定し直せるためです。
    //   （複数スレッドから並列に記録する段階になったら本数を増やします）
    //-------------------------------------------------------------------------
    ComPtr<ID3D12GraphicsCommandList> m_commandList;

    //-------------------------------------------------------------------------
    // フレームごとのフェンス値
    //
    //   m_frameFenceValues[i] は
    //   「アロケータ [i] を使ったフレームの処理が終わったときの番号」です。
    //   再び [i] を使う前にこの値を待てば、そのアロケータは安全に Reset できます。
    //
    //   初期値 0 は「まだ一度も使っていない ＝ 待つ必要なし」を意味します
    //   （フェンスの初期値も 0 なので、WaitForFenceValue(0) は即座に戻ります）。
    //-------------------------------------------------------------------------
    std::array<uint64_t, SwapChain::kBackBufferCount> m_frameFenceValues = {};

    // フレーム時間の計測（1 秒ごとに FPS をログ出力する）
    FrameTimer m_frameTimer;

    //-------------------------------------------------------------------------
    // ビューポート : バックバッファ上の「描画に使う矩形領域」と深度範囲。
    //   NDC 座標 (-1〜+1) を実際のピクセル座標へ変換する係数になります。
    //-------------------------------------------------------------------------
    D3D12_VIEWPORT m_viewport = {};

    //-------------------------------------------------------------------------
    // シザー矩形 : この矩形の外に出たピクセルを問答無用で捨てる設定。
    //   ビューポートと似ていますが役割が違います。
    //     ビューポート … 座標変換（どこに描くか）
    //     シザー       … 切り抜き（どこまで描いてよいか）
    //   設定を忘れると（＝全て 0 のままだと）1 ピクセルも描画されません。
    //   「画面が真っ黒で三角形が出ない」ときの定番の原因のひとつです。
    //-------------------------------------------------------------------------
    D3D12_RECT m_scissorRect = {};

    bool m_initialized = false;
};

} // namespace dx12
